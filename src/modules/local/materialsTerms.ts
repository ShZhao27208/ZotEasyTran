export const MATERIALS_TERMS: Record<string, string> =
  Object.fromEntries(TERM_ENTRIES);
export const MATERIALS_PHRASES: Record<string, string> =
  Object.fromEntries(PHRASE_ENTRIES);

function normalizeTermKey(text: string): string {
  return String(text || "")
    .trim()
    .toLowerCase()
    .replace(/\s+/g, " ")
    .replace(/^[^\p{L}\p{N}]+/u, "")
    .replace(/[^\p{L}\p{N}]+$/u, "");
}

/** Look up a single word or phrase in the materials termbase. */
export function lookupMaterialsTerm(raw: string): string | undefined {
  const key = normalizeTermKey(raw);
  if (!key) return undefined;
  return (
    MATERIALS_TERMS[key] ||
    MATERIALS_PHRASES[key] ||
    MATERIALS_ABBREVIATIONS[String(raw).trim()] ||
    MATERIALS_ABBREVIATIONS[String(raw).trim().toUpperCase()]
  );
}

/** Expand standalone materials abbreviations before tokenization. */
export function expandMaterialsAbbreviations(text: string): string {
  return String(text || "").replace(
    /\b(DSC|TGA|DTA|DMA|XRD|XPS|SEM|TEM|STEM|HRTEM|AFM|STM|EDS|EELS|FTIR|NMR|EIS|GPC|BET|ICP|SAXS|WAXS|DLS|CVD|PVD|ALD|PLD|MBE|MOF|COF|CNTs?|AIE|TENG|OLED|LIB)\b/g,
    (match) => MATERIALS_ABBREVIATIONS[match] || match,
  );
}
